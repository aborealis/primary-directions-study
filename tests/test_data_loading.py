"""Tests of the p0_y data-file loader on the canonical study data."""

from stat_analysis.helpers.data_loading import load_p0_y


def test_load_p0_y_400_fixed() -> None:
    """The canonical 400-chart file: 400 rows, S_obs = 179."""
    p0_list, y_list = load_p0_y('p0_y-400-fixed.txt')

    assert len(p0_list) == 400
    assert len(y_list) == 400
    assert sum(y_list) == 179
    # Sum of the p0 probabilities (expected number of deaths under H0)
    assert sum(p0_list) == 166.80263660405248
    # Every y is 0 or 1
    assert set(y_list) <= {0, 1}


def test_load_p0_y_100_fixed() -> None:
    """The canonical pilot file: 100 rows, S_obs = 49.

    The p0_y data are regenerated byte-exactly from the published
    sample by the model code of this repository (given the proprietary
    ``calc`` engine); see the data provenance note in README.
    """
    p0_list, y_list = load_p0_y('p0_y-100-fixed.txt')

    assert len(p0_list) == 100
    assert sum(y_list) == 49
    assert sum(p0_list) == 42.456294592485271
